"""Human-readable evaluation report (docs/BRIEF.md 10).

`render_report` turns the harness payload into the short report the brief asks
for: what worked, what did not, the limits. It is a skeleton by design -- the
M5 hidden-fleet run fills in the final numbers.
"""
from __future__ import annotations


def _fmt(v, nd=2, suffix="") -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.{nd}f}{suffix}"
    return f"{v}{suffix}"


def _table(methods: dict) -> str:
    rows = [
        "| method | median lead (h) | mean lead (h) | detected | missed | FA episodes | FA/week |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, m in methods.items():
        rows.append(
            f"| {name} | {_fmt(m['median_lead_h'], 1)} | {_fmt(m['mean_lead_h'], 1)} | "
            f"{m['n_detected']}/{m['n_failures']} | {m['missed']} | {m['fa_episodes']} | "
            f"{_fmt(m['fa_per_week'], 3)} |"
        )
    return "\n".join(rows)


def _per_mode(methods: dict) -> str:
    lines = ["| method | mode | n | detected | missed | median lead (h) |",
             "|---|---|---|---|---|---|"]
    for name, m in methods.items():
        for mode, d in sorted(m["per_mode"].items()):
            lines.append(
                f"| {name} | {mode} | {d['n']} | {d['detected']} | {d['missed']} | "
                f"{_fmt(d['median_lead_h'], 1)} |"
            )
    return "\n".join(lines)


def render_report(payload: dict) -> str:
    dataset = payload["dataset"]
    methods = payload["methods"]
    selected = payload["selected"]
    budget = payload["fa_budget_per_week"]

    return f"""# Evaluation report -- {dataset}

The detector answers the two problem questions with numbers, not adjectives:

1. **"Was it warning us?"** -- *lead time*: how many hours before the labelled
   failure the first alert fired inside the degradation window.
2. **"What convinces us to act?"** -- a *sustained, multi-signal* drift, beyond a
   threshold chosen from healthy commissioning data only, judged next to its
   false-alarm cost.

All thresholds and persistence parameters are chosen on **eval_dev only**.
`eval_hidden` is never used to choose anything.

## Headline

Selected method on {dataset}: **{selected}** (rule: fewest missed, then highest
median lead time among methods with <= {budget} false alarms per machine-week).

{_table(methods)}

## Lead time by degradation mode

{_per_mode(methods)}

`sudden_fault` has a very short window by construction; early warning there is
not physically possible, and we report it separately rather than hiding it in an
average.

## Method notes

- **B0 naive** -- fixed threshold on raw vibration RMS, no regime adjustment.
  Included to show what happens when you ignore operating conditions.
- **B1 EWMA/CUSUM** -- control chart on regime-adjusted residual z.
- **M main model** -- anomaly detection on rolling residual features (regime
  normalization + rolling z statistics). If M does not clearly beat B1, we keep
  B1 and say so.

## Limits and honest caveats

- All data is **simulated**; lead-time numbers demonstrate the *method*, not
  field performance.
- The detector is blind to the simulator and is evaluated on held-out seeds with
  shifted parameter ranges, but circularity can never be fully eliminated when
  we write both halves.
- Subsystem attributions are **suspected**, derived from which signals drifted,
  never a confirmed fault.
- A real plant would need at minimum a vibration sensor, motor current and
  temperature, each logged with operating load and speed, before this method
  could be applied.

_skeleton: numbers above are regenerated by `python -m analysis.eval.harness --dataset {dataset}`._
"""
